FIELD = re.compile(r'([rgb])([0-3])\[(\d+)(?::(\d+))?\]')


def endpoint(channel, end):
    return int(end) * 3 + 'rgb'.index(channel)


def body(mode):
    bits, deltas, regions, prefix, layout = LAYOUTS[mode]
    pos = 2 if mode < 2 else 5
    lines = []
    for match in FIELD.finditer(layout):
        channel, end, a, b = match.groups()
        index = endpoint(channel, end)
        a = int(a)
        b = a if b is None else int(b)
        if a >= b:  # low bit first
            count = a - b + 1
            lines.append('e[%d]|=bc6hBits(d,%d,%d)<<%d;' % (index, pos, count, b))
            pos += count
        else:  # reversed: the higher-numbered bit first
            for bit in range(b, a - 1, -1):
                lines.append('e[%d]|=bc6hBits(d,%d,1)<<%d;' % (index, pos, bit))
                pos += 1
    expect = 82 - 5 if regions == 2 else 65 - 0
    if pos != (77 if regions == 2 else 65):
        raise SystemExit('mode %d lays out to bit %d' % (mode, pos))
    return lines


